def extract_keywords(text: str, top_n: int = 30) -> List[str]:
    """
    Extracts significant single and multi-word keywords from text.
    """
    if not text:
        return []

    # Clean text to alphanumeric and basic punctuation
    cleaned = re.sub(r'[^a-zA-Z0-9\s\+\#\.\-]', ' ', text.lower())
    tokens = [t.strip() for t in cleaned.split() if len(t.strip()) > 2]

    filtered_tokens = [t for t in tokens if t not in ENGLISH_STOPWORDS and not t.isdigit()]

    counts = Counter(filtered_tokens)

    # Return top N keywords sorted by frequency
    return [word for word, count in counts.most_common(top_n)]
